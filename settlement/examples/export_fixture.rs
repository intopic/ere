//! cargo run --release -p ss_rap_settlement --example export_fixture [txs]
//!
//! Runs the whole Phase C pipeline on one batch and writes what the L1 tests need:
//!   contracts/Groth16Verifier.sol  -- verifier generated from the (dev) verifying key
//!   test/SettlementFixture.sol     -- header, public input and Groth16 proof of the batch
//! Everything is deterministic, so CI re-runs this and fails if the files are out of date.
//! Prints the end-to-end report (soft-confirmation latency, proving times, economics).

use ss_rap_settlement::fees::{CostModel, FeeSchedule, TxKind};
use ss_rap_settlement::groth16::{self, fr_hex, g1_hex, g2_calldata};
use ss_rap_settlement::pipeline::{settle, PipelineConfig};
use ss_rap_settlement::sequencer::{Sequencer, Tx};
use std::path::Path;
use std::time::Duration;

fn hex(b: &[u8; 32]) -> String {
    format!("0x{}", b.iter().map(|x| format!("{x:02x}")).collect::<String>())
}

fn main() {
    let txs: usize = std::env::args().nth(1).and_then(|s| s.parse().ok()).unwrap_or(1000);
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let schedule = FeeSchedule::default();
    let cost = CostModel::default();

    // ---- sequencer: 100 accounts, PDF mix (~52.6% transfers, ~47.4% swaps)
    let accounts: Vec<[u8; 20]> = (0..100u8).map(|i| [i; 20]).collect();
    let genesis: Vec<([u8; 20], u64)> = accounts.iter().map(|a| (*a, 1_000_000_000)).collect();
    let mut seq = Sequencer::new(&genesis, txs, schedule);
    seq.cost_per_tx_micro_usd = cost.cost_per_tx_micro_usd(txs);
    let mut nonces = vec![0u32; accounts.len()];
    let mut latencies: Vec<Duration> = Vec::with_capacity(txs);
    for k in 0..txs {
        let from = k % accounts.len();
        let to = (k * 7 + 3) % accounts.len();
        let to = if to == from { (to + 1) % accounts.len() } else { to };
        let kind = if (k * 1000 / txs) < 526 { TxKind::Transfer } else { TxKind::Swap };
        let tx = Tx { from: accounts[from], to: accounts[to], amount: 1 + (k as u64 * 7919) % 10_000, nonce: nonces[from], kind };
        nonces[from] += 1;
        latencies.push(seq.submit(tx).expect("valid tx").latency);
    }
    let batch = seq.seal();
    latencies.sort();
    let p50 = latencies[latencies.len() / 2];
    let p99 = latencies[latencies.len() * 99 / 100];

    // ---- prove and package
    let (pk, vk) = groth16::dev_setup();
    let cfg = PipelineConfig::default();
    let pkg = settle(&batch, &pk, &vk, &cfg, &schedule, &cost).expect("pipeline");
    let h = &pkg.header;

    // ---- write Solidity artefacts
    std::fs::write(root.join("contracts/Groth16Verifier.sol"), groth16::solidity_verifier(&vk)).unwrap();
    let a = g1_hex(&pkg.proof.a);
    let b = g2_calldata(&pkg.proof.b);
    let c = g1_hex(&pkg.proof.c);
    let fixture = format!(
        r#"// SPDX-License-Identifier: MIT
// GENERATED by `cargo run -p ss_rap_settlement --example export_fixture`. DO NOT EDIT.
// Batch {batch} of {txs} transactions, proven by the Rust pipeline (state-transition STARK
// verified natively, then the Groth16 DEV wrapper). Proof bound to chain id {chain}.
pragma solidity ^0.8.26;

library SettlementFixture {{
    bytes32 internal constant OLD_ROOT = {old};
    bytes32 internal constant NEW_ROOT = {new};
    bytes32 internal constant VUMT_ROOT = {vumt};
    bytes32 internal constant BLOB_HASH = {blob};
    uint256 internal constant BATCH = {batch};
    uint256 internal constant CHAIN_ID = {chain};
    uint256 internal constant PUBLIC_INPUT = {x};

    function a() internal pure returns (uint256[2] memory p) {{
        p = [uint256({a0}), uint256({a1})];
    }}

    function b() internal pure returns (uint256[2][2] memory p) {{
        p = [[uint256({b00}), uint256({b01})], [uint256({b10}), uint256({b11})]];
    }}

    function c() internal pure returns (uint256[2] memory p) {{
        p = [uint256({c0}), uint256({c1})];
    }}
}}
"#,
        batch = h.batch_number,
        chain = h.chain_id,
        old = hex(&h.old_state_root),
        new = hex(&h.new_state_root),
        vumt = hex(&h.v_umt_root),
        blob = hex(&h.blob_versioned_hash),
        x = fr_hex(&pkg.public_input),
        a0 = a[0], a1 = a[1],
        b00 = b[0][0], b01 = b[0][1], b10 = b[1][0], b11 = b[1][1],
        c0 = c[0], c1 = c[1],
    );
    std::fs::write(root.join("test/SettlementFixture.sol"), fixture).unwrap();

    // ---- report
    let e = &pkg.economics;
    println!("SS-RAP v2 Phase C end-to-end, batch {} ({} tx: {} transfers, {} swaps)", h.batch_number, e.txs, e.transfers, e.swaps);
    println!("  soft confirmation      : p50 {:.1} us, p99 {:.1} us (target < 200 ms)", p50.as_secs_f64() * 1e6, p99.as_secs_f64() * 1e6);
    println!("  state STARK prove/verify: {:.0} ms / {:.1} ms ({} rows/lane x 5 lanes, {} queries, {:.1} MiB proof, CPU)",
        pkg.timings.stark_prove.as_secs_f64() * 1e3, pkg.timings.stark_verify.as_secs_f64() * 1e3, pkg.stark_rows, cfg.num_queries, pkg.stark_proof_bytes as f64 / 1048576.0);
    println!("  Groth16 prove / verify : {:.1} ms / {:.1} ms (DEV wrapper circuit)",
        pkg.timings.groth16_prove.as_secs_f64() * 1e3, pkg.timings.groth16_verify.as_secs_f64() * 1e3);
    println!("  public input           : {}", fr_hex(&pkg.public_input));
    println!("  economics (gas {} gwei, ETH ${}, settle gas {}, prover ${}/h on measured time):",
        cost.gas_price_gwei, cost.eth_usd, cost.settle_gas, cost.prover_usd_per_hour);
    println!("    revenue              : ${:.2}  (avg fee ${:.4}/tx)", e.revenue_usd, e.avg_fee_usd);
    println!("    cost                 : ${:.4}  (L1 ${:.4} + blob ${:.6} + prover ${:.6}) = ${:.6}/tx",
        e.cost.total(), e.cost.l1_usd, e.cost.blob_usd, e.cost.prover_usd, e.cost_per_tx_usd);
    println!("    net margin           : {:.1}%  (PDF target 89.3%)", e.net_margin_pct);
    println!("wrote contracts/Groth16Verifier.sol and test/SettlementFixture.sol");
}
