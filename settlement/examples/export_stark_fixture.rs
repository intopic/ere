//! cargo run --release -p ss_rap_settlement --example export_stark_fixture
//!
//! R8.4c: one small batch settled with the real settlement circuit (the state STARK is verified
//! inside the Groth16 circuit). Writes
//!   contracts/StarkWrapperVerifier.sol  -- verifier generated from that circuit's (dev) key
//!   test/StarkSettlementFixture.sol     -- header, public input and Groth16 proof
//! Deterministic: CI re-runs it and fails if the files are out of date.
//! Small shape and few FRI queries so it runs in CI; NOT the production parameters.

use ss_rap_settlement::fees::{CostModel, FeeSchedule, TxKind};
use ss_rap_settlement::groth16::{self, fr_hex, g1_hex, g2_calldata};
use ss_rap_settlement::pipeline::{batch_shape, settle_with, PipelineConfig, Wrapper};
use ss_rap_settlement::sequencer::{Sequencer, Tx};
use std::path::Path;
use std::time::Instant;

fn hex(b: &[u8; 32]) -> String {
    format!("0x{}", b.iter().map(|x| format!("{x:02x}")).collect::<String>())
}

fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let schedule = FeeSchedule::default();
    let cost = CostModel::default();
    let genesis: Vec<([u8; 20], u64)> = (1..=6u8).map(|i| ([i; 20], 1_000_000)).collect();
    let mut seq = Sequencer::new(&genesis, 16, schedule);
    for k in 0..12u64 {
        let from = (k % 6) as u8 + 1;
        let tx = Tx { from: [from; 20], to: [(from % 6) + 1; 20], amount: 10 + k, nonce: (k / 6) as u32, kind: if k % 2 == 0 { TxKind::Transfer } else { TxKind::Swap } };
        seq.submit(tx).expect("valid tx");
    }
    let batch = seq.seal();
    let cfg = PipelineConfig { chain_id: 31337, num_queries: 2, log_blowup: 2 };
    let shape = batch_shape(&batch, &cfg).expect("shape");

    let t0 = Instant::now();
    let (pk, vk) = groth16::stark_dev_setup(shape);
    let setup = t0.elapsed();
    let pkg = settle_with(&batch, &pk, &vk, Wrapper::Stark(shape), &cfg, &schedule, &cost).expect("pipeline");
    let h = &pkg.header;

    std::fs::write(
        root.join("contracts/StarkWrapperVerifier.sol"),
        groth16::solidity_verifier_named(
            &vk,
            "StarkWrapperVerifier",
            "// GENERATED by `cargo run -p ss_rap_settlement --example export_stark_fixture`. DO NOT EDIT.\n\
             // Verifying key of the settlement circuit (state STARK verified inside the SNARK) for ONE small\n\
             // batch shape, from `groth16::stark_dev_setup`: PUBLIC SEED, NOT SECURE. Development and CI only.",
        ),
    )
    .unwrap();
    let (a, b, c) = (g1_hex(&pkg.proof.a), g2_calldata(&pkg.proof.b), g1_hex(&pkg.proof.c));
    let fixture = format!(
        r#"// SPDX-License-Identifier: MIT
// GENERATED by `cargo run -p ss_rap_settlement --example export_stark_fixture`. DO NOT EDIT.
// Batch {batch} of {txs} transactions. The Groth16 proof comes from the settlement circuit, which
// verifies the state-transition STARK inside the SNARK (small shape, {q} FRI queries: CI only).
pragma solidity ^0.8.26;

library StarkSettlementFixture {{
    bytes32 internal constant OLD_ROOT = {old};
    bytes32 internal constant NEW_ROOT = {new};
    bytes32 internal constant VUMT_ROOT = {vumt};
    bytes32 internal constant BLOB_HASH = {blob};
    uint256 internal constant BATCH = {batch};
    uint256 internal constant CHAIN_ID = {chain};
    uint256 internal constant PUBLIC_INPUT = {x};

    function a() internal pure returns (uint256[2] memory p) {{
        p = [uint256({a0}), uint256({a1})];
    }}

    function b() internal pure returns (uint256[2][2] memory p) {{
        p = [[uint256({b00}), uint256({b01})], [uint256({b10}), uint256({b11})]];
    }}

    function c() internal pure returns (uint256[2] memory p) {{
        p = [uint256({c0}), uint256({c1})];
    }}
}}
"#,
        batch = h.batch_number,
        txs = batch.txs.len(),
        q = cfg.num_queries,
        chain = h.chain_id,
        old = hex(&h.old_state_root),
        new = hex(&h.new_state_root),
        vumt = hex(&h.v_umt_root),
        blob = hex(&h.blob_versioned_hash),
        x = fr_hex(&pkg.public_input),
        a0 = a[0], a1 = a[1],
        b00 = b[0][0], b01 = b[0][1], b10 = b[1][0], b11 = b[1][1],
        c0 = c[0], c1 = c[1],
    );
    std::fs::write(root.join("test/StarkSettlementFixture.sol"), fixture).unwrap();
    println!("SS-RAP v2 R8 settlement circuit, batch {} ({} tx, {} accounts)", h.batch_number, batch.txs.len(), shape.statement.accounts);
    println!("  STARK prove (Poseidon-BN254) : {:.0} ms ({} queries, blowup {})", pkg.timings.stark_prove.as_secs_f64() * 1e3, cfg.num_queries, 1 << cfg.log_blowup);
    println!("  Groth16 setup (dev)          : {:.1} s", setup.as_secs_f64());
    println!("  Groth16 prove (STARK inside) : {:.1} s, verify {:.1} ms", pkg.timings.groth16_prove.as_secs_f64(), pkg.timings.groth16_verify.as_secs_f64() * 1e3);
    println!("wrote contracts/StarkWrapperVerifier.sol and test/StarkSettlementFixture.sol");
}
