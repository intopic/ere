//! Groth16 over BN254 for L1 settlement, and the Solidity verifier generated from the real VK.
//!
//! What this replaces: v2.0 shipped a verification key made of known multiples of the
//! generators (ALPHA = [11]G1, BETA = [5]G2, ...). Anyone who knows those scalars can forge a
//! passing proof. Here the VK comes from an actual Groth16 setup and the Solidity verifier is
//! generated from it, so the contract, the Rust prover and the fixtures always agree.
//!
//! IMPORTANT, read before any deployment:
//! 1. `dev_setup` uses a fixed public seed, so its toxic waste is public. It exists only so that
//!    CI and local tests are reproducible. Production needs a multi-party ceremony.
//! 2. `SettlementCircuit` is the DEV wrapper: it binds the batch public input but does not yet
//!    verify the STARK inside the SNARK. The STARK is verified natively by the aggregator
//!    (`pipeline.rs`). The production wrapper (STARK verifier as a BN254 circuit, or the STARK
//!    verifier run inside a zkVM with a Groth16 back end) replaces this circuit without
//!    changing the contract interface: one public input, same pairing check.

use ark_bn254::{Bn254, Fq, Fq2, Fr, G1Affine, G2Affine};
use ark_ff::{BigInteger, PrimeField};
use ark_groth16::{Groth16, Proof, ProvingKey, VerifyingKey};
use ark_relations::lc;
use ark_relations::r1cs::{ConstraintSynthesizer, ConstraintSystemRef, SynthesisError};
use ark_snark::SNARK;
use rand_chacha::rand_core::SeedableRng;
use rand_chacha::ChaCha20Rng;

/// DEV wrapper circuit: public input x, private witness w, constraint w * 1 = x.
#[derive(Clone)]
pub struct SettlementCircuit {
    pub public_input: Option<Fr>,
}

impl ConstraintSynthesizer<Fr> for SettlementCircuit {
    fn generate_constraints(self, cs: ConstraintSystemRef<Fr>) -> Result<(), SynthesisError> {
        let x = cs.new_input_variable(|| self.public_input.ok_or(SynthesisError::AssignmentMissing))?;
        let w = cs.new_witness_variable(|| self.public_input.ok_or(SynthesisError::AssignmentMissing))?;
        cs.enforce_constraint(lc!() + w, lc!() + ark_relations::r1cs::Variable::One, lc!() + x)?;
        Ok(())
    }
}

pub const DEV_SETUP_SEED: [u8; 32] = *b"SS-RAP-v2-DEV-SETUP-NOT-SECURE!!";

/// Reproducible setup for tests and CI. NOT SECURE (public seed).
pub fn dev_setup() -> (ProvingKey<Bn254>, VerifyingKey<Bn254>) {
    let mut rng = ChaCha20Rng::from_seed(DEV_SETUP_SEED);
    Groth16::<Bn254>::circuit_specific_setup(SettlementCircuit { public_input: None }, &mut rng).expect("setup")
}

pub fn prove(pk: &ProvingKey<Bn254>, public_input: Fr, seed: u64) -> Proof<Bn254> {
    let mut rng = ChaCha20Rng::seed_from_u64(seed);
    Groth16::<Bn254>::prove(pk, SettlementCircuit { public_input: Some(public_input) }, &mut rng).expect("prove")
}

pub fn verify(vk: &VerifyingKey<Bn254>, public_input: Fr, proof: &Proof<Bn254>) -> bool {
    Groth16::<Bn254>::verify(vk, &[public_input], proof).unwrap_or(false)
}

// ---------------------------------------------------------------------------------------------
// EVM encoding
// ---------------------------------------------------------------------------------------------

pub fn fq_hex(x: &Fq) -> String {
    format!("0x{}", hex32(&x.into_bigint().to_bytes_be()))
}

pub fn fr_hex(x: &Fr) -> String {
    format!("0x{}", hex32(&x.into_bigint().to_bytes_be()))
}

fn hex32(be: &[u8]) -> String {
    let mut s = String::with_capacity(64);
    for _ in be.len()..32 {
        s.push_str("00");
    }
    for b in be {
        s.push_str(&format!("{b:02x}"));
    }
    s
}

pub fn g1_hex(p: &G1Affine) -> [String; 2] {
    [fq_hex(&p.x), fq_hex(&p.y)]
}

/// EIP-197 order for constants: [x_imag, x_real, y_imag, y_real].
pub fn g2_eip197(p: &G2Affine) -> [String; 4] {
    let (x, y): (&Fq2, &Fq2) = (&p.x, &p.y);
    [fq_hex(&x.c1), fq_hex(&x.c0), fq_hex(&y.c1), fq_hex(&y.c0)]
}

/// Calldata order used by `verifyProof(.., uint256[2][2] b, ..)`: b[0] = [x_real, x_imag],
/// b[1] = [y_real, y_imag] (the contract swaps into EIP-197 order itself).
pub fn g2_calldata(p: &G2Affine) -> [[String; 2]; 2] {
    [[fq_hex(&p.x.c0), fq_hex(&p.x.c1)], [fq_hex(&p.y.c0), fq_hex(&p.y.c1)]]
}

/// Generates the Solidity verifier from a verifying key.
pub fn solidity_verifier(vk: &VerifyingKey<Bn254>) -> String {
    assert_eq!(vk.gamma_abc_g1.len(), 2, "exactly one public input");
    let a = g1_hex(&vk.alpha_g1);
    let b = g2_eip197(&vk.beta_g2);
    let g = g2_eip197(&vk.gamma_g2);
    let d = g2_eip197(&vk.delta_g2);
    let ic0 = g1_hex(&vk.gamma_abc_g1[0]);
    let ic1 = g1_hex(&vk.gamma_abc_g1[1]);
    format!(
        r#"// SPDX-License-Identifier: MIT
// GENERATED by `cargo run -p ss_rap_settlement --example export_fixture`. DO NOT EDIT.
// Verifying key from `groth16::dev_setup()`: PUBLIC SEED, NOT SECURE. Development and CI only.
// Production must regenerate this file from a multi-party trusted-setup ceremony.
pragma solidity ^0.8.26;

import {{IGroth16Verifier}} from "./IGroth16Verifier.sol";

contract Groth16Verifier is IGroth16Verifier {{
    uint256 internal constant R_MOD = 21888242871839275222246405745257275088548364400416034343698204186575808495617;
    uint256 internal constant P_MOD = 21888242871839275222246405745257275088696311157297823662689037894645226208583;
    // Bounded gas for the precompiles (EIP-1108 prices: ecAdd 150, ecMul 6000, pairing 45000 + 34000/pair).
    // A failing precompile consumes all gas it was given; the caps keep an invalid proof cheap to reject.
    uint256 internal constant EC_ADD_GAS = 500;
    uint256 internal constant EC_MUL_GAS = 7000;
    uint256 internal constant PAIRING_GAS = 200000;

    uint256 internal constant ALPHA_X = {ax};
    uint256 internal constant ALPHA_Y = {ay};
    uint256 internal constant BETA_X1 = {b0};
    uint256 internal constant BETA_X2 = {b1};
    uint256 internal constant BETA_Y1 = {b2};
    uint256 internal constant BETA_Y2 = {b3};
    uint256 internal constant GAMMA_X1 = {g0};
    uint256 internal constant GAMMA_X2 = {g1};
    uint256 internal constant GAMMA_Y1 = {g2};
    uint256 internal constant GAMMA_Y2 = {g3};
    uint256 internal constant DELTA_X1 = {d0};
    uint256 internal constant DELTA_X2 = {d1};
    uint256 internal constant DELTA_Y1 = {d2};
    uint256 internal constant DELTA_Y2 = {d3};
    uint256 internal constant IC0_X = {i0x};
    uint256 internal constant IC0_Y = {i0y};
    uint256 internal constant IC1_X = {i1x};
    uint256 internal constant IC1_Y = {i1y};

    /// @inheritdoc IGroth16Verifier
    function verifyProof(
        uint256[2] calldata a,
        uint256[2][2] calldata b,
        uint256[2] calldata c,
        uint256 publicInput
    ) external view returns (bool) {{
        if (publicInput >= R_MOD) return false;
        if (
            a[0] >= P_MOD || a[1] >= P_MOD || b[0][0] >= P_MOD || b[0][1] >= P_MOD ||
            b[1][0] >= P_MOD || b[1][1] >= P_MOD || c[0] >= P_MOD || c[1] >= P_MOD
        ) return false;

        // K = IC0 + publicInput * IC1  (ecMul 0x07, ecAdd 0x06)
        uint256[3] memory mulIn = [IC1_X, IC1_Y, publicInput];
        uint256[2] memory k;
        bool ok;
        assembly {{
            ok := staticcall(EC_MUL_GAS, 0x07, mulIn, 0x60, k, 0x40)
        }}
        if (!ok) return false;
        uint256[4] memory addIn = [IC0_X, IC0_Y, k[0], k[1]];
        assembly {{
            ok := staticcall(EC_ADD_GAS, 0x06, addIn, 0x80, k, 0x40)
        }}
        if (!ok) return false;

        // e(-A, B) * e(ALPHA, BETA) * e(K, GAMMA) * e(C, DELTA) == 1  (ecPairing 0x08)
        uint256[24] memory p;
        p[0] = a[0];
        p[1] = a[1] == 0 ? 0 : P_MOD - a[1];
        p[2] = b[0][1];
        p[3] = b[0][0];
        p[4] = b[1][1];
        p[5] = b[1][0];
        p[6] = ALPHA_X;
        p[7] = ALPHA_Y;
        p[8] = BETA_X1;
        p[9] = BETA_X2;
        p[10] = BETA_Y1;
        p[11] = BETA_Y2;
        p[12] = k[0];
        p[13] = k[1];
        p[14] = GAMMA_X1;
        p[15] = GAMMA_X2;
        p[16] = GAMMA_Y1;
        p[17] = GAMMA_Y2;
        p[18] = c[0];
        p[19] = c[1];
        p[20] = DELTA_X1;
        p[21] = DELTA_X2;
        p[22] = DELTA_Y1;
        p[23] = DELTA_Y2;
        uint256[1] memory out;
        assembly {{
            ok := staticcall(PAIRING_GAS, 0x08, p, 0x300, out, 0x20)
        }}
        return ok && out[0] == 1;
    }}
}}
"#,
        ax = a[0], ay = a[1],
        b0 = b[0], b1 = b[1], b2 = b[2], b3 = b[3],
        g0 = g[0], g1 = g[1], g2 = g[2], g3 = g[3],
        d0 = d[0], d1 = d[1], d2 = d[2], d3 = d[3],
        i0x = ic0[0], i0y = ic0[1], i1x = ic1[0], i1y = ic1[1],
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use ark_ec::AffineRepr;

    #[test]
    fn prove_and_verify_roundtrip() {
        let (pk, vk) = dev_setup();
        let x = Fr::from(123456789u64);
        let proof = prove(&pk, x, 1);
        assert!(verify(&vk, x, &proof));
        assert!(!verify(&vk, x + Fr::from(1u64), &proof), "proof is bound to its public input");
    }

    #[test]
    fn vk_is_not_a_small_multiple_of_the_generator() {
        // Regression for the v2.0 demo key: alpha must not be [k]G1 for small k.
        let (_, vk) = dev_setup();
        let g = G1Affine::generator();
        let mut acc = g.into_group();
        for _ in 1..1000 {
            assert_ne!(ark_ec::CurveGroup::into_affine(acc), vk.alpha_g1);
            acc += g;
        }
    }

    #[test]
    fn solidity_has_all_constants() {
        let (_, vk) = dev_setup();
        let s = solidity_verifier(&vk);
        for name in ["ALPHA_X", "BETA_X1", "GAMMA_Y2", "DELTA_X2", "IC1_Y"] {
            assert!(s.contains(&format!("uint256 internal constant {name} = 0x")), "{name}");
        }
    }
}
